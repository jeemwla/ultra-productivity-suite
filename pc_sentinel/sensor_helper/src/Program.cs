// Ultra Suite Sensor Helper: entry point.
//   --service --edition Public|Dev       run as the Windows service (started by Windows, never by hand)
//   --console --edition Public|Dev       run in a console window for troubleshooting
//   --provision --edition E [--pawnio] [--result <folder>\sensor-setup-result.ini]
//                                        elevated one-time setup (the installer or PC Sentinel's retry button)
//   --unprovision --edition E [--result ...]
//                                        elevated removal of this edition's service and files (PawnIO stays)
//   --version
using System;
using System.IO;
using System.Reflection;
using System.ServiceProcess;
using System.Text;

namespace UltraSuite.SensorHelper
{
    public static class Program
    {
        public static string Version
        {
            get
            {
                var v = typeof(Program).Assembly.GetName().Version;
                return v == null ? "0.0.0" : v.ToString(3);
            }
        }

        [STAThread]
        public static int Main(string[] args)
        {
            // Dependencies built for slightly different assembly versions load from this folder (binding redirects are
            // also generated by the build; this is the fallback).
            AppDomain.CurrentDomain.AssemblyResolve += ResolveFromOwnFolder;
            Options o;
            try { o = Options.Parse(args); }
            catch (ArgumentException e)
            {
                Console.Error.WriteLine(e.Message);
                return 2;
            }
            switch (o.Mode)
            {
                case "version":
                    Console.WriteLine(Version);
                    return 0;
                case "service":
                    ServiceBase.Run(new HelperService(o.Edition));
                    return 0;
                case "console":
                    return RunConsole(o.Edition);
                case "provision":
                {
                    var log = Logger(o.Edition);
                    var r = Provisioner.Provision(o.Edition, o.PawnIo, AppDomain.CurrentDomain.BaseDirectory, log);
                    Provisioner.WriteResult(o.Result, r);
                    log("provision: pawnio=" + r.PawnIo + " exit=" + r.PawnIoExit + " service=" + r.Service);
                    return r.Service == "running" ? 0 : 1;
                }
                case "unprovision":
                {
                    var log = Logger(o.Edition);
                    var r = Provisioner.Unprovision(o.Edition, log);
                    Provisioner.WriteResult(o.Result, r);
                    return r.Service == "removed" ? 0 : 1;
                }
            }
            return 2;
        }

        static int RunConsole(HelperEdition edition)
        {
            using (var host = new HelperHost(edition, Console.WriteLine))
            {
                host.Start();
                Console.WriteLine("Serving http://127.0.0.1:" + edition.Port + "/data.json (read-only). Press Enter to stop.");
                Console.ReadLine();
            }
            return 0;
        }

        static Assembly ResolveFromOwnFolder(object sender, ResolveEventArgs e)
        {
            try
            {
                string name = new AssemblyName(e.Name).Name;
                string path = Path.Combine(AppDomain.CurrentDomain.BaseDirectory, name + ".dll");
                return File.Exists(path) ? Assembly.LoadFrom(path) : null;
            }
            catch (Exception) { return null; }
        }

        /// <summary>A small log next to the installed helper (Program Files), capped at 256 KB.</summary>
        public static Action<string> Logger(HelperEdition edition)
        {
            string dir = edition.InstallDirectory(Provisioner.ProgramFiles());
            string path = Path.Combine(dir, "helper.log");
            object gate = new object();
            return msg =>
            {
                try
                {
                    lock (gate)
                    {
                        if (!Directory.Exists(dir)) return;
                        var fi = new FileInfo(path);
                        if (fi.Exists && fi.Length > 256 * 1024) fi.Delete();
                        File.AppendAllText(path, DateTime.UtcNow.ToString("u") + " " + msg + "\r\n", new UTF8Encoding(false));
                    }
                }
                catch (Exception) { }
            };
        }
    }

    /// <summary>The reader plus the loopback server, shared by service and console modes.</summary>
    public sealed class HelperHost : IDisposable
    {
        readonly HelperEdition _edition;
        readonly Action<string> _log;
        HardwareReader _reader;
        LoopbackServer _server;

        public HelperHost(HelperEdition edition, Action<string> log)
        {
            _edition = edition; _log = log;
        }

        public void Start()
        {
            _reader = new HardwareReader(_edition, _log);
            _reader.Start();
            _server = new LoopbackServer(_edition.Port, new Router(_edition.Port, _reader.Data, _reader.Health));
            _server.Start();
            _log("listening on 127.0.0.1:" + _edition.Port);
        }

        public void Dispose()
        {
            if (_server != null) _server.Dispose();
            if (_reader != null) _reader.Dispose();
        }
    }

    public sealed class HelperService : ServiceBase
    {
        readonly HelperEdition _edition;
        HelperHost _host;

        public HelperService(HelperEdition edition)
        {
            _edition = edition;
            ServiceName = edition.ServiceName;
            CanStop = true;
            CanShutdown = true;
            CanPauseAndContinue = false;
            AutoLog = true;
        }

        protected override void OnStart(string[] args)
        {
            _host = new HelperHost(_edition, Program.Logger(_edition));
            _host.Start(); // a port already in use throws here, so Windows records the failure and retries
        }

        protected override void OnStop()
        {
            if (_host != null) _host.Dispose();
            _host = null;
        }

        protected override void OnShutdown()
        {
            OnStop();
        }
    }
}
